// Raw "merchant-side" product data. This is deliberately messy and
// inconsistently formatted per item — it's what gets rendered into the demo
// storefront HTML, and what the onboarding scraper (src/lib/scraper.ts) has
// to crawl and normalize. Messiness is intentional: it's the source of the
// ambiguity flags shown at onboarding.

export interface RawProduct {
  sku: string;
  title: string;
  brand: string;
  category: string;
  subcategory: string;
  imageEmoji: string;
  description: string;
  // Free-text spec block, exactly as it would appear scraped off a real page.
  specText: string;
  // Messy price string, as rendered on the page (not a clean number).
  priceText: string;
  stockText: string;
  discountPct: number;
  // A pricier alternative with more of what the buyer likely wants — surfaced
  // as the "worth considering" stretch pick in buyer chat.
  upgradeSku?: string;
  // Complementary items — surfaced as cross-sell / bundle-building candidates.
  pairsWithSkus?: string[];
}

